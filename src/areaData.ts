export function getAreaPath(area: Pick<AreaData, 'governorateId' | 'slug'>): string {
  return `/locations/${area.governorateId}/${area.slug}`;
}

export function findArea(governorateId?: string, areaId?: string): AreaData | undefined {
  return areaData.find((area) => area.governorateId === governorateId && area.slug === areaId);
}

export function findAreaByPath(pathname: string): AreaData | undefined {
  return areaData.find((area) => getAreaPath(area) === pathname);
}
