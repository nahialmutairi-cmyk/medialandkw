export function findClientLandingByPath(pathname: string) {
  const normalized = pathname !== '/' && pathname.endsWith('/') ? pathname.slice(0, -1) : pathname;
  return clientLandings.find((client) => client.path === normalized);
}

export function clientLandingUrl(path: string) {
  return `${siteConfig.siteUrl}${path}`;
}
